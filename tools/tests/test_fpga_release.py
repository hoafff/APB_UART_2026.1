"""Release gates: reject incomplete STA, bad pins, unreviewed warnings and tampering.

Fixtures are captured Quartus 25.1 post-fit reports, not generated by the checker.
"""
import importlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
FIXTURES = Path(__file__).parent / 'fixtures'


class ReleaseTests(unittest.TestCase):
    def setUp(self):
        try:
            self.check = importlib.import_module('fpga_checks')
        except ModuleNotFoundError:
            self.fail('FPGA release validation is not implemented')
        self.timing = (FIXTURES / 'fpga_timing.tsv').read_text()

    def test_actual_post_fit_report_passes(self):
        result = self.check.validate_timing(self.timing)
        self.assertEqual(result['corners'], 3)
        self.assertEqual(result['worst_slack_ns']['hold'], 0.181)

    def test_missing_or_truncated_report_rejected(self):
        for value in ('', self.timing.replace('STATUS\tPOST_FIT_AUDIT_PASS', '')):
            with self.subTest(value=value[-30:]), self.assertRaises(ValueError):
                self.check.validate_timing(value)

    def test_negative_nonfinite_and_missing_slack_rejected(self):
        for value in ('-0.001', 'nan', 'inf', 'n/a', ''):
            with self.subTest(value=value), self.assertRaises(ValueError):
                self.check.validate_timing(self.timing.replace('\t5.016\n', '\t' + value + '\n'))

    def test_missing_metric_or_corner_rejected(self):
        for match in ('\treset_recovery\t', '\tmin_pulse_width\t', '7_slow_1200mv_0c'):
            text = '\n'.join(line for line in self.timing.splitlines() if match not in line)
            with self.subTest(match=match), self.assertRaises(ValueError):
                self.check.validate_timing(text)

    def test_zero_timed_paths_rejected(self):
        with self.assertRaises(ValueError):
            self.check.validate_timing(self.timing.replace('\tsetup\t20\t', '\tsetup\t0\t'))

    def test_missing_or_untimed_chain_rejected(self):
        for match in ('CHAIN_EDGE\treset_sync', 'CHAIN_TIMING\tMIN_fast_1200mv_0c\thold'):
            text = '\n'.join(line for line in self.timing.splitlines() if match not in line)
            with self.subTest(match=match), self.assertRaises(ValueError):
                self.check.validate_timing(text)

    def test_extra_or_missing_waiver_rejected(self):
        for text in (self.timing.replace('INPUT_WAIVER\tGPIO_UART_RX', 'INPUT_WAIVER\tCLOCK_50'),
                     self.timing + '\nINPUT_WAIVER\tNEW_PORT\n'):
            with self.assertRaises(ValueError):
                self.check.validate_timing(text)

    def test_unconstrained_and_ignored_sdc_rejected(self):
        for text in (self.timing.replace('UCP\tIllegal Clocks\t0\t0', 'UCP\tIllegal Clocks\t1\t0'),
                     self.timing.replace('COUNT\tignored_sdc\t0', 'COUNT\tignored_sdc\t1')):
            with self.assertRaises(ValueError):
                self.check.validate_timing(text)

    def test_duplicate_metric_rejected(self):
        metric = next(line for line in self.timing.splitlines() if line.startswith('METRIC'))
        with self.assertRaises(ValueError):
            self.check.validate_timing(self.timing + '\n' + metric)

    def test_fitted_pins_match_all_65_ports(self):
        pins = (FIXTURES / 'fpga_pins.pin').read_text()
        profile = json.loads((ROOT / 'docs/spec/pins.json').read_text())
        self.assertEqual(self.check.validate_pins(pins, profile)['pin_bits'], 65)
        for text in (pins.replace('AB21', 'ZZ99'), pins.replace('GPIO_UART_RX', 'RENAMED_RX'),
                     pins.replace('GPIO_UART_TX                 : AB22      : output',
                                  'GPIO_UART_TX                 : AB22      : input')):
            with self.assertRaises(ValueError):
                self.check.validate_pins(text, profile)

    def test_warning_gate_rejects_new_or_changed_warning(self):
        log = (FIXTURES / 'fpga_compile.txt').read_text()
        result = self.check.review_warnings(log)
        self.assertEqual(result['10335'], 3)
        for changed in (log + '\nWarning (99999): New issue\n',
                        log.replace('Pin "LEDG[2]" is stuck at GND', 'Pin "GPIO_UART_TX" is stuck at GND'),
                        log + '\nCritical Warning (332148): Timing requirements not met\n'):
            with self.assertRaises(ValueError):
                self.check.review_warnings(changed)

    def test_hash_gate_rejects_tampered_source_and_sof(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            for name in ('source.sv', 'image.sof'):
                (root / name).write_bytes(b'abc')
            files = {name: 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'
                     for name in ('source.sv', 'image.sof')}
            self.assertEqual(self.check.verify_hashes(root, files), 2)
            for name in files:
                (root / name).write_bytes(b'tampered')
                with self.assertRaises(ValueError):
                    self.check.verify_hashes(root, files)
                (root / name).write_bytes(b'abc')
            (root / 'image.sof').unlink()
            with self.assertRaises(ValueError):
                self.check.verify_hashes(root, files)

    def test_empty_or_escaping_manifest_rejected(self):
        with tempfile.TemporaryDirectory() as folder:
            for files in ({}, {'../outside': '0' * 64}, {'C:/outside': '0' * 64}):
                with self.assertRaises(ValueError):
                    self.check.verify_hashes(Path(folder), files)

    def test_simulation_completion_is_revalidated(self):
        validator = getattr(self.check, 'validate_simulation', None)
        self.assertTrue(callable(validator), 'Simulation evidence validation is missing')
        log = (FIXTURES / 'fpga_simulation.txt').read_text()
        result = validator(log)
        self.assertEqual(result['system_checks'], 4027274)
        self.assertEqual(result['controller_checks'], 46)
        self.assertEqual(result['onehot_checks'], 2361)
        self.assertEqual(result['onehot_frames'], 192)

    def test_simulation_missing_partial_or_error_log_rejected(self):
        validator = getattr(self.check, 'validate_simulation', None)
        self.assertTrue(callable(validator), 'Simulation evidence validation is missing')
        log = (FIXTURES / 'fpga_simulation.txt').read_text()
        for text in ('', log.replace('SYS_TEST_COMPLETED|checks=46', 'INCOMPLETE'),
                     log.replace('frames=192', 'frames=1'),
                     log + '\n# ** Error: a real assertion failed\n',
                     log + '\n# Errors: 1, Warnings: 0\n'):
            with self.assertRaises(ValueError):
                validator(text)


if __name__ == '__main__':
    unittest.main()
